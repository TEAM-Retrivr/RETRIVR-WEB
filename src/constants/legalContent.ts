export type LegalSection = {
  title: string;
  body: string;
};

const parseSectionsByTitlePattern = (
  content: string,
  titlePattern: RegExp,
): LegalSection[] => {
  const lines = content.split("\n");
  const sections: LegalSection[] = [];
  let currentTitle = "";
  let currentBody: string[] = [];

  const flushTitled = () => {
    if (!currentTitle) return;
    sections.push({
      title: currentTitle,
      body: currentBody.join("\n").trim(),
    });
    currentTitle = "";
    currentBody = [];
  };

  const flushPreamble = () => {
    const body = currentBody.join("\n").trim();
    if (!body) {
      currentBody = [];
      return;
    }
    sections.push({ title: "", body });
    currentBody = [];
  };

  for (const line of lines) {
    if (titlePattern.test(line.trim())) {
      if (currentTitle) {
        flushTitled();
      } else {
        flushPreamble();
      }
      currentTitle = line.trim();
      continue;
    }
    currentBody.push(line);
  }
  if (currentTitle) {
    flushTitled();
  } else {
    flushPreamble();
  }
  return sections;
};

export const parseLegalSections = (content: string): LegalSection[] =>
  parseSectionsByTitlePattern(content, /^제\d+조|^부칙$/);

export const parseNumberedLegalSections = (content: string): LegalSection[] =>
  parseSectionsByTitlePattern(content, /^\d+\.\s/);

